using System.Text.RegularExpressions;
using MimeKit;

namespace Switchboard.Modules.Messaging.Inbound;

public enum AutomaticKind
{
    None,
    /// <summary>Out-of-office and other replies a person's mailbox sent by itself.</summary>
    AutoReply,
    /// <summary>Machine mail: bulk, lists, alerts. Processed, but never answered automatically.</summary>
    AutoGenerated,
    /// <summary>Delivery failure report.</summary>
    Bounce,
}

public sealed record AutomaticCheck(AutomaticKind Kind, string Reason);

public enum AuthVerdict
{
    /// <summary>No usable Authentication-Results header.</summary>
    None,
    Pass,
    Fail,
}

public sealed record AuthCheck(AuthVerdict Verdict, string? Spf, string? Dkim, string? Dmarc, string? AuthServId)
{
    public string Describe() => Verdict == AuthVerdict.None && Spf is null && Dkim is null && Dmarc is null
        ? "No authentication results on the message"
        : $"SPF {Spf ?? "none"}, DKIM {Dkim ?? "none"}, DMARC {Dmarc ?? "none"}";
}

/// <summary>Header checks for mail loops (SR-EML-1) and sender authentication (SR-EML-2).</summary>
public static partial class MailAnalysis
{
    public static AutomaticCheck DetectAutomatic(MimeMessage message)
    {
        if (IsBounce(message, out var bounceReason))
        {
            return new(AutomaticKind.Bounce, bounceReason);
        }

        var autoSubmitted = message.Headers["Auto-Submitted"]?.Trim().ToLowerInvariant();
        if (autoSubmitted is { Length: > 0 } && !autoSubmitted.StartsWith("no", StringComparison.Ordinal))
        {
            return autoSubmitted.StartsWith("auto-replied", StringComparison.Ordinal)
                ? new(AutomaticKind.AutoReply, $"Auto-Submitted: {autoSubmitted}")
                : new(AutomaticKind.AutoGenerated, $"Auto-Submitted: {autoSubmitted}");
        }
        foreach (var name in new[] { "X-Autoreply", "X-Autorespond", "X-Autoresponder" })
        {
            if (message.Headers.Contains(name))
            {
                return new(AutomaticKind.AutoReply, $"{name} header");
            }
        }
        if (message.Headers["X-Autogenerated"] is { } generated)
        {
            return generated.Contains("reply", StringComparison.OrdinalIgnoreCase)
                ? new(AutomaticKind.AutoReply, "X-Autogenerated: Reply")
                : new(AutomaticKind.AutoGenerated, $"X-Autogenerated: {generated.Trim()}");
        }
        var precedence = message.Headers["Precedence"]?.Trim().ToLowerInvariant();
        if (precedence is "auto_reply")
        {
            return new(AutomaticKind.AutoReply, "Precedence: auto_reply");
        }
        if (precedence is "bulk" or "junk" or "list")
        {
            return new(AutomaticKind.AutoGenerated, $"Precedence: {precedence}");
        }
        if (IsNullSender(message))
        {
            return new(AutomaticKind.AutoGenerated, "Empty return path (null sender)");
        }
        if (AutoReplySubject().IsMatch(message.Subject ?? ""))
        {
            return new(AutomaticKind.AutoReply, "Subject looks like an automatic reply");
        }
        if (message.Headers.Contains("List-Id") || message.Headers.Contains("List-Unsubscribe"))
        {
            return new(AutomaticKind.AutoGenerated, "Mailing list headers");
        }
        return new(AutomaticKind.None, "Written by a person");
    }

    private static bool IsBounce(MimeMessage message, out string reason)
    {
        if (message.Body is MultipartReport { ReportType: var type } && string.Equals(type, "delivery-status", StringComparison.OrdinalIgnoreCase))
        {
            reason = "Delivery status report";
            return true;
        }
        var from = message.From.Mailboxes.FirstOrDefault()?.LocalPart ?? "";
        var looksLikeDaemon = from.Equals("mailer-daemon", StringComparison.OrdinalIgnoreCase) || from.Equals("postmaster", StringComparison.OrdinalIgnoreCase);
        if ((looksLikeDaemon || IsNullSender(message)) && BounceSubject().IsMatch(message.Subject ?? ""))
        {
            reason = "Delivery failure notice";
            return true;
        }
        reason = "";
        return false;
    }

    private static bool IsNullSender(MimeMessage message)
    {
        var returnPath = message.Headers["Return-Path"];
        return returnPath is not null && returnPath.Trim() is "<>" or "";
    }

    /// <summary>
    /// Reads SPF, DKIM and DMARC from <c>Authentication-Results</c> (RFC 8601). Only the topmost
    /// header counts (added by your own server), or the first one from <paramref name="trustedAuthServId"/>.
    /// Senders can forge lower headers, so those are never read.
    /// </summary>
    public static AuthCheck ReadAuthentication(MimeMessage message, string? trustedAuthServId)
    {
        foreach (var header in message.Headers.Where(h => h.Field.Equals("Authentication-Results", StringComparison.OrdinalIgnoreCase)))
        {
            var value = Comments().Replace(header.Value ?? "", " ");
            var parts = value.Split(';', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries);
            if (parts.Length == 0)
            {
                continue;
            }
            var authServId = parts[0].Split(' ', StringSplitOptions.RemoveEmptyEntries).FirstOrDefault();
            if (trustedAuthServId is { Length: > 0 } trusted && !string.Equals(authServId, trusted.Trim(), StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            string? spf = null, dkim = null, dmarc = null;
            var aligned = false;
            var fromDomain = message.From.Mailboxes.FirstOrDefault()?.Domain;
            foreach (var part in parts.Skip(1))
            {
                var m = MethodResult().Match(part);
                if (!m.Success)
                {
                    continue;
                }
                var method = m.Groups[1].Value.ToLowerInvariant();
                var result = m.Groups[2].Value.ToLowerInvariant();
                switch (method)
                {
                    case "spf":
                        spf ??= result;
                        aligned |= result == "pass" && Aligned(Property(part, "smtp.mailfrom") ?? Property(part, "smtp.helo"), fromDomain);
                        break;
                    case "dkim":
                        // Several signatures: any pass counts.
                        dkim = dkim == "pass" ? dkim : result;
                        aligned |= result == "pass" && Aligned(Property(part, "header.d") ?? Property(part, "header.i"), fromDomain);
                        break;
                    case "dmarc":
                        dmarc ??= result;
                        break;
                }
            }
            return new AuthCheck(Verdict(spf, dkim, dmarc, aligned), spf, dkim, dmarc, authServId);
        }
        return new AuthCheck(AuthVerdict.None, null, null, null, null);
    }

    /// <summary>
    /// DMARC decides when present. Without it, an SPF or DKIM pass only counts when its domain matches
    /// the From domain (relaxed alignment); a pass for some other domain says nothing about the sender.
    /// </summary>
    private static AuthVerdict Verdict(string? spf, string? dkim, string? dmarc, bool aligned)
    {
        if (dmarc == "pass")
        {
            return AuthVerdict.Pass;
        }
        if (dmarc == "fail")
        {
            return AuthVerdict.Fail;
        }
        if (aligned)
        {
            return AuthVerdict.Pass;
        }
        if (spf == "fail" || dkim == "fail")
        {
            return AuthVerdict.Fail;
        }
        return AuthVerdict.None;
    }

    private static string? Property(string part, string name)
    {
        var m = Regex.Match(part, $@"(?:^|\s){Regex.Escape(name)}\s*=\s*""?([^\s;""]+)", RegexOptions.IgnoreCase, TimeSpan.FromMilliseconds(250));
        return m.Success ? m.Groups[1].Value : null;
    }

    /// <summary>Relaxed alignment: the same domain, or one is a subdomain of the other.</summary>
    internal static bool Aligned(string? identity, string? fromDomain)
    {
        if (string.IsNullOrEmpty(identity) || string.IsNullOrEmpty(fromDomain))
        {
            return false;
        }
        var domain = (identity.Contains('@') ? identity[(identity.LastIndexOf('@') + 1)..] : identity).Trim().TrimEnd('.').ToLowerInvariant();
        var from = fromDomain.Trim().TrimEnd('.').ToLowerInvariant();
        if (!domain.Contains('.') || !from.Contains('.'))
        {
            return false;
        }
        return domain == from || from.EndsWith("." + domain, StringComparison.Ordinal) || domain.EndsWith("." + from, StringComparison.Ordinal);
    }

    [GeneratedRegex(@"\([^()]*\)", RegexOptions.None, matchTimeoutMilliseconds: 250)]
    private static partial Regex Comments();

    [GeneratedRegex(@"^\s*(spf|dkim|dmarc)\s*=\s*([a-z]+)", RegexOptions.IgnoreCase, matchTimeoutMilliseconds: 250)]
    private static partial Regex MethodResult();

    [GeneratedRegex(@"^\s*(automatic reply|auto[- ]?reply|autoreply|auto[- ]?response|out of (the )?office|ooo\b|abwesenheit|r[ée]ponse automatique)", RegexOptions.IgnoreCase, matchTimeoutMilliseconds: 250)]
    private static partial Regex AutoReplySubject();

    [GeneratedRegex(@"(undeliver|delivery (status notification|failure|has failed)|mail delivery (failed|subsystem)|returned mail|failure notice|delivery report)", RegexOptions.IgnoreCase, matchTimeoutMilliseconds: 250)]
    private static partial Regex BounceSubject();
}
